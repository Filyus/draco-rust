//! Turning ETC1S blocks into ETC1 and ETC2, the block formats a phone takes.
//!
//! Ported from `BinomialLLC/basis_universal`, revision `9bebe16`, Apache-2.0:
//! the `cETC1` case of `basisu_lowlevel_etc1s_transcoder::transcode_slice`,
//! `convert_etc1s_to_etc2_eac_a8`, and the `decoder_etc_block` and
//! `eac_block` layouts in `transcoder/basisu_transcoder.cpp`.
//!
//! The colour half costs almost nothing, because an ETC1S block *is* an ETC1
//! block: one differential base colour, one intensity table for both halves,
//! and the sixteen selectors as they stand. Writing it out is filling in the
//! two bits ETC1S leaves implicit — no flip, differential mode — and copying
//! the rest.
//!
//! The alpha half is a real conversion. ETC2's EAC alpha interpolates over
//! eight steps against a base and a multiplier, where ETC1S has four steps on
//! an intensity curve, so a block is answered from a table of solved endpoints
//! — the same shape as ETC1S to BC1 and BC4, and small like BC4's because one
//! channel needs only 1024 solutions.
//!
//! Which matters where: a desktop browser offers the BC family and nothing
//! else, while on Android and iOS ETC2 is at essentially 100% and s3tc at
//! 28% and 40%. Without this a phone can only take pixels, at eight times the
//! video memory, which is the machine that can least afford it.


/// Selector ranges the encoder produces, in table order.
const EAC_SELECTOR_RANGES: [(u8, u8); 4] = [(0, 3), (1, 3), (0, 2), (1, 2)];

/// The selector bits of a constant-alpha EAC block: every texel takes step 4.
const EAC_CONSTANT_SELECTORS: [u8; 6] = [0x92, 0x49, 0x24, 0x92, 0x49, 0x24];

/// One ETC1 block: a differential base colour, two intensity tables, selectors.
#[derive(Debug, Clone, Copy, Default)]
pub struct Etc1Block {
    bytes: [u8; 8],
}

impl Etc1Block {
    /// The eight bytes a GPU expects.
    pub fn to_bytes(self) -> [u8; 8] {
        self.bytes
    }

    /// Write `count` bits at `offset`, counting from the block's last byte.
    ///
    /// ETC1 numbers its bits from the most significant end of a big-endian
    /// 64-bit word, which is why the byte index runs backwards.
    fn set_bits(&mut self, offset: u32, count: u32, value: u32) {
        let byte = 7 - (offset >> 3) as usize;
        let shift = offset & 7;
        let mask = (1u32 << count) - 1;
        self.bytes[byte] &= !((mask << shift) as u8);
        self.bytes[byte] |= (value << shift) as u8;
    }
}

/// Convert one ETC1S block into the ETC1 block it already is.
pub fn convert_etc1(color5: [u8; 3], inten5: u8, selectors: [u8; 4]) -> Etc1Block {
    let mut block = Etc1Block::default();
    // No flip, and differential mode: the second subblock's delta is zero, so
    // both halves take the same base colour. Khronos's own KTX2 decoder makes
    // the same choice, and a flipped block would describe the same pixels
    // differently for no reason.
    block.bytes[3] = 0b10;
    // Base colour, five bits per channel.
    block.set_bits(59, 5, color5[0] as u32);
    block.set_bits(51, 5, color5[1] as u32);
    block.set_bits(43, 5, color5[2] as u32);
    // One intensity table for both subblocks.
    block.bytes[3] |= ((inten5 as u32 & 7) << 5) as u8;
    block.bytes[3] |= ((inten5 as u32 & 7) << 2) as u8;

    // ETC1 does not store a texel's two bits side by side: it keeps two bit
    // planes, the low bits in the last two bytes and the high bits in the two
    // before them, indexed column by column. And its four colours are ordered
    // differently again, so the value itself is permuted on the way.
    const TO_ETC1: [u8; 4] = [3, 2, 0, 1];
    for x in 0..4usize {
        for (y, &row) in selectors.iter().enumerate() {
            let selector = (row >> (x * 2)) & 3;
            let value = TO_ETC1[selector as usize];
            let bit = x * 4 + y;
            let byte = 7 - (bit >> 3);
            let mask = 1u8 << (bit & 7);
            block.bytes[byte] = (block.bytes[byte] & !mask) | ((value & 1) << (bit & 7));
            block.bytes[byte - 2] = (block.bytes[byte - 2] & !mask) | ((value >> 1) << (bit & 7));
        }
    }
    block
}

/// One EAC alpha block: a base value, a table and multiplier, and selectors.
#[derive(Debug, Clone, Copy, Default)]
pub struct EacBlock {
    base: u8,
    table: u8,
    multiplier: u8,
    selectors: [u8; 6],
}

impl EacBlock {
    /// The eight bytes a GPU expects.
    pub fn to_bytes(self) -> [u8; 8] {
        let mut bytes = [0u8; 8];
        bytes[0] = self.base;
        bytes[1] = (self.multiplier << 4) | (self.table & 15);
        bytes[2..8].copy_from_slice(&self.selectors);
        bytes
    }
}

/// Convert one block of an ETC1S alpha slice into an EAC alpha block.
pub fn convert_eac_alpha(color5: [u8; 3], inten5: u8, selectors: [u8; 4]) -> EacBlock {
    let (lowest, highest) = crate::etc1s::selector_extremes(selectors);
    let colors = crate::etc1s::block_colors5(color5, inten5);

    if lowest == highest {
        // One value everywhere. Table 13 with a multiplier of one and every
        // texel on the middle step reproduces the base exactly.
        return EacBlock {
            base: colors[lowest as usize][0],
            table: 13,
            multiplier: 1,
            selectors: EAC_CONSTANT_SELECTORS,
        };
    }

    let range = EAC_SELECTOR_RANGES
        .iter()
        .position(|(low, high)| *low == lowest && *high == highest)
        .unwrap_or(0);
    let (base, table_multiplier, translation) = ETC1S_TO_EAC_A8
        [(color5[0] as usize + inten5 as usize * 32) * EAC_SELECTOR_RANGES.len() + range];

    // EAC packs its sixteen three-bit selectors into 48 bits, column by column
    // from the top: texel (x, y) sits at bit 45 - (y + x * 4) * 3.
    let mut bits = 0u64;
    for (y, &row) in selectors.iter().enumerate() {
        for x in 0..4usize {
            let selector = (row >> (x * 2)) & 3;
            let translated = ((translation >> (selector * 3)) & 7) as u64;
            bits |= translated << (45 - (y + x * 4) * 3);
        }
    }

    EacBlock {
        base,
        // The packed field is table in the high nibble, multiplier in the low
        // one - the reverse of what the reference's own comment on it says.
        table: table_multiplier >> 4,
        multiplier: table_multiplier & 15,
        selectors: [
            (bits >> 40) as u8,
            (bits >> 32) as u8,
            (bits >> 24) as u8,
            (bits >> 16) as u8,
            (bits >> 8) as u8,
            bits as u8,
        ],
    }
}

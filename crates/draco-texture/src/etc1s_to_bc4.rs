/// One BC4 block: two endpoints and sixteen three-bit selectors.
#[derive(Debug, Clone, Copy, Default)]
pub struct Bc4Block {
    low: u8,
    high: u8,
    selectors: [u8; 6],
}

impl Bc4Block {
    /// The eight bytes a GPU expects.
    pub fn to_bytes(self) -> [u8; 8] {
        let mut bytes = [0u8; 8];
        bytes[0] = self.low;
        bytes[1] = self.high;
        bytes[2..8].copy_from_slice(&self.selectors);
        bytes
    }

    fn set_selector(&mut self, texel: usize, value: u8) {
        let bit = texel * 3;
        let byte = bit >> 3;
        let offset = bit & 7;
        let mut window = self.selectors[byte] as u32;
        if byte < 5 {
            window |= (self.selectors[byte + 1] as u32) << 8;
        }
        window &= !(7u32 << offset);
        window |= (value as u32) << offset;
        self.selectors[byte] = window as u8;
        if byte < 5 {
            self.selectors[byte + 1] = (window >> 8) as u8;
        }
    }
}

/// Convert one block of an ETC1S alpha slice into a BC4 block.
///
/// The alpha value is the block colour's red channel: an alpha slice is a grey
/// ETC1S image, so its three channels hold the same number.
pub fn convert(color5: [u8; 3], inten5: u8, selectors: [u8; 4]) -> Bc4Block {
    let (lowest, highest) = crate::etc1s_to_bc1::selector_extremes(selectors);
    let colors = crate::etc1s::block_colors5(color5, inten5);

    // One value everywhere: both endpoints land on it and every selector is 0.
    if lowest == highest {
        let value = colors[lowest as usize][0];
        return Bc4Block {
            low: value,
            high: value,
            selectors: [0; 6],
        };
    }

    // Two values: the endpoints are those two exactly, so there is nothing to
    // search for and nothing to lose.
    if crate::etc1s_to_bc1::unique_selectors(selectors) == 2 {
        let mut block = Bc4Block {
            low: colors[lowest as usize][0],
            high: colors[highest as usize][0],
            selectors: [0; 6],
        };
        for texel in 0..16 {
            let selector = (selectors[texel / 4] >> ((texel % 4) * 2)) & 3;
            block.set_selector(texel, u8::from(selector == highest));
        }
        return block;
    }

    let range = SELECTOR_RANGES
        .iter()
        .position(|(low, high)| *low == lowest && *high == highest)
        .unwrap_or(0);
    let (low, high, translation) =
        ETC1S_TO_BC4[(color5[0] as usize + inten5 as usize * 32) * SELECTOR_RANGES.len() + range];

    let mut block = Bc4Block {
        low,
        high,
        selectors: [0; 6],
    };
    for texel in 0..16 {
        let selector = (selectors[texel / 4] >> ((texel % 4) * 2)) & 3;
        block.set_selector(texel, ((translation >> (selector * 3)) & 7) as u8);
    }
    block
}
